    fun errorBody(code: AppErrorCode): String = when (code) {
        AppErrorCode.NO_DEVICE -> errNoDeviceBody
        AppErrorCode.USB_PERMISSION -> errPermissionBody
        AppErrorCode.BOOTLOADER -> errBootloaderBody
