    fun phaseTitle(phase: FlashPhase): String = when (phase) {
        FlashPhase.Disconnected -> phaseDisconnected
        FlashPhase.Connecting -> phaseConnecting
        FlashPhase.Detecting -> phaseDetecting
        FlashPhase.Ready -> phaseReady
        FlashPhase.EnteringBootloader -> phaseBootloader
        FlashPhase.Erasing -> phaseErasing
        FlashPhase.Writing -> phaseWriting
        FlashPhase.Verifying -> phaseVerifying
