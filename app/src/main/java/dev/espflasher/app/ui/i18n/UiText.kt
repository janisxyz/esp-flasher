    fun errorTitle(code: AppErrorCode): String = when (code) {
        AppErrorCode.NO_DEVICE -> errNoDeviceTitle
        AppErrorCode.USB_PERMISSION -> errPermissionTitle
        AppErrorCode.BOOTLOADER -> errBootloaderTitle
        AppErrorCode.DISCONNECT -> errDisconnectTitle
        AppErrorCode.WRONG_FIRMWARE -> errFirmwareTitle
        AppErrorCode.VERIFICATION -> errVerifyTitle
        AppErrorCode.CANCELLED -> errCancelledTitle
